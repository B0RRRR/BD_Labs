const fmt = (x, d = 1) => {
  const [i, f] = Number(x).toFixed(d).split(".");
  const ii = i.replace(/\B(?=(\d{3})+(?!\d))/g, " ");
  return f ? `${ii},${f}` : ii;
};
// «в N раз» / «в N раза»: число со словом в нужной форме
