-- =====================================================================
-- migration.sql — расширение модели ЛР №1 для аналитики (ЛР №2)
--
-- Зачем:
--   * tasks.estimate_hours — плановая трудоёмкость задачи в часах.
--     Без неё у задач нет ни одного числового показателя, кроме приоритета:
--     нельзя посчитать объём работ проекта, нагрузку исполнителя, прогресс
--     в часах (SUM / AVG).
--     NULL — задача ещё не оценена; 0 — трудоёмкость пренебрежимо мала.
--   * tasks.completed_at — момент фактического завершения задачи.
--     Без него нельзя проверить, сдана ли задача в срок (due_date), и
--     посчитать время выполнения (completed_at - created_at).
--     Заполнен тогда и только тогда, когда status = 'done'.
--
-- Существующие данные сохраняются: новые столбцы добавляются без NOT NULL,
-- затем для 8 задач из ЛР №1 заполняются значения, и только после этого
-- добавляются ограничения.
--
-- created_at у задач из data.sql — момент загрузки скрипта, а не реальная
-- дата. Его тоже уточняем: иначе completed_at оказался бы раньше created_at,
-- а задачи завершённого в июне проекта — созданными в октябре.
-- =====================================================================
BEGIN;

-- 1. Новые столбцы (пока без ограничений)
ALTER TABLE tasks ADD COLUMN estimate_hours NUMERIC(5, 1);
ALTER TABLE tasks ADD COLUMN completed_at   TIMESTAMP;

-- 2. Заполнение для существующих задач (ищем по уникальной паре проект + название)
UPDATE tasks t
SET created_at     = v.created_at::timestamp,
    estimate_hours = v.estimate_hours::numeric,
    completed_at   = v.completed_at::timestamp
FROM (VALUES
    ('Мобильное приложение', 'Собрать требования',              '2026-09-01 10:00', '16',  '2026-09-09 17:00'),
    ('Мобильное приложение', 'Сверстать экран входа',           '2026-09-12 11:00', '12',  NULL),
    ('Мобильное приложение', 'Интеграция с платёжной системой', '2026-09-15 09:30', '24',  NULL),
    ('Мобильное приложение', 'Написать тест-кейсы',             '2026-09-20 14:00', '8',   NULL),
    ('Мобильное приложение', 'Настроить push-уведомления',      '2026-10-05 10:00', NULL,  NULL),
    ('Корпоративный сайт',   'Сверстать главную страницу',      '2026-03-05 10:00', '20',  '2026-04-14 18:00'),
    ('Корпоративный сайт',   'Проверить адаптивность',          '2026-04-20 12:00', '6',   '2026-06-03 16:00'),
    ('CRM-система',          'Собрать требования',              '2026-10-02 10:00', NULL,  NULL)
) AS v(project, title, created_at, estimate_hours, completed_at)
JOIN projects p ON p.name = v.project
WHERE t.project_id = p.project_id
  AND t.title = v.title;

-- 3. Ограничения (проверяют и только что заполненные строки)
ALTER TABLE tasks ADD CONSTRAINT chk_tasks_estimate
    CHECK (estimate_hours >= 0);

-- задача завершена <=> известен момент завершения
ALTER TABLE tasks ADD CONSTRAINT chk_tasks_completed
    CHECK ((status = 'done') = (completed_at IS NOT NULL));

ALTER TABLE tasks ADD CONSTRAINT chk_tasks_completed_after_created
    CHECK (completed_at IS NULL OR completed_at >= created_at);

COMMIT;
